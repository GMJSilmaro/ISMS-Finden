export type SeedProfile =
  | "minimal"
  | "full"
  | "core"
  | "status"
  | "brs"
  | "schedules"
  | "branches"
  | "psg"
  | "warehouse";

export function resolveSeedProfile(): SeedProfile {
  const raw = process.env.SEED_PROFILE?.trim().toLowerCase();
  if (
    raw === "full" ||
    raw === "core" ||
    raw === "status" ||
    raw === "brs" ||
    raw === "schedules" ||
    raw === "branches" ||
    raw === "psg" ||
    raw === "warehouse" ||
    raw === "minimal"
  ) {
    return raw;
  }
  return "minimal";
}
